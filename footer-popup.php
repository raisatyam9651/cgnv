<script>
  (function() {
    const popupOverlay = document.getElementById("sixSecondPopup");
    const closeBtn = document.getElementById("closePopupBtn");
    
    setTimeout(function() { console.log("Popup script initialized"); if (popupOverlay) popupOverlay.classList.add("show-popup"); }, 6000);

    closeBtn.addEventListener("click", function() {
      popupOverlay.classList.remove("show-popup");
      sessionStorage.setItem("popupClosed", "true");
    });

    popupOverlay.addEventListener("click", function(e) {
      if (e.target === popupOverlay) {
        popupOverlay.classList.remove("show-popup");
        sessionStorage.setItem("popupClosed", "true");
      }
    });
    // Form submission logic via Fetch API
    const popupForm = popupOverlay ? popupOverlay.querySelector('form') : null;
    if (popupForm) {
      popupForm.classList.remove('bform');
      
      popupForm.addEventListener('submit', function(e) {
        e.preventDefault();
        
        const name = this.querySelector('.name').value;
        const email = this.querySelector('.email').value;
        const phone = this.querySelector('.phone').value;
        const captcha = this.querySelector("input[name='captcha']").value;
        
        if (name === '' || email === '' || phone === '') {
          alert('Please fill required fields');
          return false;
        }

        if (captcha !== '139') {
          alert('Please fill the correct number for the captcha');
          return false;
        }

        const formData = new FormData(this);
        const submitBtn = this.querySelector("button[type='submit']");
        const originalText = submitBtn.textContent;
        submitBtn.textContent = 'Sending...';
        submitBtn.disabled = true;

        fetch(this.action, {
          method: this.method,
          body: formData
        })
        .then(response => response.text())
        .then(data => {
          submitBtn.textContent = originalText;
          submitBtn.disabled = false;
          
          if (data.includes('Please fill the correct number')) {
            alert('Please fill the correct number for the Captcha');
          } else {
            window.dataLayer = window.dataLayer || []; 
            window.dataLayer.push({'event':'form-submit-success'});
            window.location.href = 'thankyou.php';
          }
        })
        .catch(error => {
          console.error('Error submitting form:', error);
          submitBtn.textContent = originalText;
          submitBtn.disabled = false;
          alert('There was an error submitting the form. Please try again.');
        });
      });
    }
  })();
</script>




